\getenv platform_password PLATFORM_DATABASE_PASSWORD
\getenv domain_password DOMAIN_DATABASE_PASSWORD
CREATE ROLE platform_runtime LOGIN PASSWORD :'platform_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE ROLE domain_runtime LOGIN PASSWORD :'domain_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE DATABASE platform_service OWNER platform_runtime;
CREATE DATABASE domain_service OWNER domain_runtime;
REVOKE CONNECT ON DATABASE platform_service FROM PUBLIC;
REVOKE CONNECT ON DATABASE domain_service FROM PUBLIC;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;
GRANT CONNECT ON DATABASE platform_service TO platform_runtime;
GRANT CONNECT ON DATABASE domain_service TO domain_runtime;
